class TYMarks:

    def __init__(self, theory, practical):
        self.theory = theory
        self.practical = practical

    # Getters
    def getTheory(self):
        return self.theory

    def getPractical(self):
        return self.practical

    # Setters
    def setTheory(self, theory):
        self.theory = theory

    def setPractical(self, practical):
        self.practical = practical